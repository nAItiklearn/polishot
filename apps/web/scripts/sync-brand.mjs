// Reads the brand master SVGs from packages/brand/assets and writes:
//   - components/brand/paths.generated.ts  (the path data, so the logo is inlined as React SVG)
//   - public/brand/*.svg                   (the same masters, served as static files)
// Run after the masters change:  node apps/web/scripts/sync-brand.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.join(here, '..');
const assets = path.join(web, '..', '..', 'packages', 'brand', 'assets');

const read = (name) => readFileSync(path.join(assets, name), 'utf8');

/** Paths in document order with the role their fill plays: ink (stem, letters) or accent (the print). */
function parsePaths(svg) {
  const out = [];
  for (const match of svg.matchAll(/<path\b([^>]*)\/>/g)) {
    const attrs = match[1];
    const d = /\sd="([^"]+)"/.exec(attrs)?.[1];
    const fill = /\sfill="([^"]+)"/.exec(attrs)?.[1]?.toUpperCase();
    if (!d || !fill) throw new Error(`Unexpected path in brand SVG: ${attrs.slice(0, 80)}`);
    const role = fill === '#C8471D' || fill === '#EE7444' ? 'accent' : 'ink';
    out.push({ d, role, evenodd: /fill-rule="evenodd"/.test(attrs) });
  }
  return out;
}

const mark = read('logo-mark.svg');
const lockup = read('logo-lockup-dark.svg');

const markViewBox = /viewBox="([^"]+)"/.exec(mark)[1];
const lockupViewBox = /viewBox="([^"]+)"/.exec(lockup)[1];
const lockupTransform = /<g transform="([^"]+)"/.exec(lockup)?.[1] ?? '';

const body = `// GENERATED by scripts/sync-brand.mjs from packages/brand/assets. Do not edit by hand.
export interface BrandPath {
  d: string;
  /** "ink" follows the text colour, "accent" follows the persimmon accent. */
  role: 'ink' | 'accent';
  evenodd: boolean;
}

export const MARK_VIEWBOX = ${JSON.stringify(markViewBox)};
export const MARK_PATHS: BrandPath[] = ${JSON.stringify(parsePaths(mark), null, 2)};

export const LOCKUP_VIEWBOX = ${JSON.stringify(lockupViewBox)};
export const LOCKUP_TRANSFORM = ${JSON.stringify(lockupTransform)};
export const LOCKUP_PATHS: BrandPath[] = ${JSON.stringify(parsePaths(lockup), null, 2)};
`;

mkdirSync(path.join(web, 'components', 'brand'), { recursive: true });
writeFileSync(path.join(web, 'components', 'brand', 'paths.generated.ts'), body);

mkdirSync(path.join(web, 'public', 'brand'), { recursive: true });
for (const name of ['logo-mark.svg', 'logo-mark-mono.svg', 'logo-lockup-light.svg', 'logo-lockup-dark.svg']) {
  copyFileSync(path.join(assets, name), path.join(web, 'public', 'brand', name));
}
console.log('brand assets synced');

import org.jetbrains.kotlin.gradle.dsl.JvmTarget

// :quicksend is the Polishot quick-send protocol (docs/QUICKSEND.md) as a pure Kotlin/JVM library: JCA only,
// no Android dependencies, so it runs under plain JUnit on any JDK 17+. Plugin and org.json versions come from
// gradle/libs.versions.toml. JUnit Jupiter is not in the catalog (the app modules use JUnit 4), so its version
// is pinned here; move it into the catalog if another module starts using JUnit 5.

plugins {
    alias(libs.plugins.kotlin.jvm)
}

java {
    sourceCompatibility = JavaVersion.VERSION_17
    targetCompatibility = JavaVersion.VERSION_17
}

kotlin {
    compilerOptions {
        jvmTarget.set(JvmTarget.JVM_17)
    }
}

dependencies {
    testImplementation(platform("org.junit:junit-bom:6.1.3"))
    testImplementation("org.junit.jupiter:junit-jupiter")
    testRuntimeOnly("org.junit.platform:junit-platform-launcher")
    testImplementation(libs.org.json)
}

tasks.test {
    useJUnitPlatform()
    // The shared interop vectors, generated by the Rust crate (packages/quicksend-vectors).
    val vectors = rootProject.projectDir.resolve("../../packages/quicksend-vectors/vectors.json").canonicalPath
    systemProperty("quicksend.vectors", vectors)
    inputs.file(vectors)
}
